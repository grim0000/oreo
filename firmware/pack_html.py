import gzip
import hashlib
import os

# Paths relative to this script so the walk engine folder packs its own UI
here = os.path.dirname(os.path.abspath(__file__))
html_file = os.path.join(here, 'controller.html')
out_file = os.path.join(here, 'src', 'controller_html_gz.h')

with open(html_file, 'rb') as f:
    data = f.read()
# the thumbnails' address carries the sheet's fingerprint (phones cache /sprites.webp for a week)
with open(os.path.join(here, 'assets', 'sprites.webp'), 'rb') as f:
    data = data.replace(b'__SPR_VER__', hashlib.sha1(f.read()).hexdigest()[:10].encode())

# Gzip the data
compressed_data = gzip.compress(data)

# Create C header
hex_array = ', '.join([f'0x{b:02x}' for b in compressed_data])

header_content = f"""// Auto-generated by pack_html.py
#ifndef CONTROLLER_HTML_GZ_H
#define CONTROLLER_HTML_GZ_H

#include <pgmspace.h>

const size_t controller_html_gz_len = {len(compressed_data)};
const uint8_t controller_html_gz[] PROGMEM = {{
    {hex_array}
}};

#endif // CONTROLLER_HTML_GZ_H
"""

with open(out_file, 'w') as f:
    f.write(header_content)

print(f"Packed {len(data)} bytes to {len(compressed_data)} bytes in {out_file}")


# the servo calibration page (/calibrate)
cal_file = os.path.join(here, 'calibrate.html')
cal_out = os.path.join(here, 'src', 'calibrate_html_gz.h')
with open(cal_file, 'rb') as f:
    cdata = gzip.compress(f.read())
with open(cal_out, 'w') as f:
    f.write("// Auto-generated by pack_html.py (calibrate.html)\n#pragma once\n#include <pgmspace.h>\n"
            f"const size_t calibrate_html_gz_len = {len(cdata)};\nconst uint8_t calibrate_html_gz[] PROGMEM = {{\n    "
            + ', '.join(f'0x{b:02x}' for b in cdata) + "\n};\n")
print(f"Packed calibrate.html to {len(cdata)} bytes")


# the servo mapping page (/servomap)
sm_file = os.path.join(here, 'servomap.html')
sm_out = os.path.join(here, 'src', 'servomap_html_gz.h')
with open(sm_file, 'rb') as f:
    mdata = gzip.compress(f.read())
with open(sm_out, 'w') as f:
    f.write("// Auto-generated by pack_html.py (servomap.html)\n#pragma once\n#include <pgmspace.h>\n"
            f"const size_t servomap_html_gz_len = {len(mdata)};\nconst uint8_t servomap_html_gz[] PROGMEM = {{\n    "
            + ', '.join(f'0x{b:02x}' for b in mdata) + "\n};\n")
print(f"Packed servomap.html to {len(mdata)} bytes")


# the face style / play scene thumbnails (/sprites.webp; rendered with tools/face_preview.cpp)
spr_file = os.path.join(here, 'assets', 'sprites.webp')
spr_out = os.path.join(here, 'src', 'sprites_webp.h')
with open(spr_file, 'rb') as f:
    sdata = f.read()
with open(spr_out, 'w') as f:
    f.write("// Auto-generated by pack_html.py (assets/sprites.webp)\n#pragma once\n#include <pgmspace.h>\n"
            f"const size_t sprites_webp_len = {len(sdata)};\nconst uint8_t sprites_webp[] PROGMEM = {{\n    "
            + ', '.join(f'0x{b:02x}' for b in sdata) + "\n};\n")
print(f"Packed sprites.webp ({len(sdata)} bytes)")
